    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
    String identidad = txtIdentidad.getText().trim();
    String nombre = txtNombre.getText().trim();
    String apellido = txtApellidos.getText().trim();
    String telefono = txtTelefono.getText().trim();
    String correo = txtCorreo.getText().trim();
    String fecha = txtFechaNacimiento.getText().trim();

    if (identidad.isEmpty() || nombre.isEmpty()
            || apellido.isEmpty() || fecha.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Complete los campos obligatorios.");
        return;
    }

    java.time.LocalDate.parse(fecha);

    modelo.Persona persona = new modelo.Persona();
    persona.setIdentidad(identidad);
    persona.setNombre(nombre);
    persona.setApellido(apellido);
    persona.setTelefono(telefono);
    persona.setCorreo(correo);
    persona.setFechaNacimiento(fecha);

    dao.PersonaDAOImpl daoPersona = new dao.PersonaDAOImpl();
    daoPersona.insertar(persona);

    javax.swing.JOptionPane.showMessageDialog(
        this, "Operación de guardado ejecutada.");
    cargarTabla();
} catch (java.time.format.DateTimeParseException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Fecha inválida. Use AAAA-MM-DD.");
} catch (Exception e) {
    

    if (e.getMessage() != null &&
        e.getMessage().contains("SQLITE_CONSTRAINT_UNIQUE")) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Ya existe una persona registrada con este número de identidad.",
            "Identidad duplicada",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

    } else {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error al guardar: " + e.getMessage()
        );
    
}
}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
    String identidad = txtIdentidad.getText().trim();

if (identidad.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingrese un número de identidad.");
    return;
}

try {
    PersonaDAOImpl daoPersona = new PersonaDAOImpl();
    Optional<Persona> resultado =
        daoPersona.buscarPorIdentidad(identidad);

    if (resultado.isPresent()) {
        Persona persona = resultado.get();

        txtId.setText(String.valueOf(persona.getId()));
        txtNombre.setText(persona.getNombre());
        txtApellidos.setText(persona.getApellido());
        txtTelefono.setText(persona.getTelefono());
        txtCorreo.setText(persona.getCorreo());
        txtFechaNacimiento.setText(
            persona.getFechaNacimiento());

        javax.swing.JOptionPane.showMessageDialog(
            this, "Persona encontrada correctamente.");
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "No se encontró la persona.");
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al buscar: " + e.getMessage());
}    
    }//GEN-LAST:event_btnBuscarActionPerformed

