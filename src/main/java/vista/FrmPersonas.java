    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try {
    int id = Integer.parseInt(txtId.getText().trim());

    int opcion = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "¿Está seguro de eliminar esta persona?",
        "Confirmar eliminación",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (opcion == javax.swing.JOptionPane.YES_OPTION) {

        PersonaDAOImpl daoPersona = new PersonaDAOImpl();

        if (daoPersona.buscarPorId(id).isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "No se encontró la persona."
            );
            return;
        }

        daoPersona.eliminar(id);

        javax.swing.JOptionPane.showMessageDialog(
            this, "Persona eliminada correctamente."
        );

        btnNuevo.doClick();
        cargarTabla();
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Debe buscar una persona con ID válido."
    );

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al eliminar: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnEliminarActionPerformed

